import type { FeedItem, State } from "../state";
import { promptViews } from "../state";
import { pct, tplus } from "../format";

const INK = { reduce: "#b8290f", hedge: "#8a5a00", hold: "#13294b", good: "#1f5f3a", poor: "#b8290f" } as const;
const ROT = ["rotate(-0.8deg)", "rotate(0.6deg)", "rotate(-0.4deg)"];
const SHOWN = 80; // the list scrolls inside its panel

function Slip({ item, i, auto }: { item: FeedItem; i: number; auto: boolean }) {
  let who: string, head: string, quote: string, stamp: string, ink: string;
  if (item.type === "agent_decision") {
    who = item.agent.toUpperCase();
    head = `${tplus(item.t)} · ${item.corridor} · RISK ${pct(item.risk)}%`;
    quote = item.explanation; // cached text exactly as the server sent it
    stamp = item.action.toUpperCase();
    ink = INK[item.action];
  } else if (item.type === "player_move") {
    who = auto ? "AUTOPILOT (YOUR MOVE)" : "YOU";
    head = `${tplus(item.t)} · ${item.corridor}`;
    quote = auto ? `Autopilot chose ${item.action} on ${item.corridor}, following Sentinel.` : `You chose ${item.action} on ${item.corridor}.`;
    stamp = item.action.toUpperCase();
    ink = INK[item.action];
  } else {
    who = "OUTCOME";
    head = tplus(item.t);
    quote = item.reason;
    stamp = item.result === "good" ? "✓ GOOD" : "✗ POOR";
    ink = INK[item.result];
  }
  return (
    <li className={`slip slip-${item.type}`} style={{ transform: ROT[i % 3] }}>
      <div className="slip-head"><span className="slip-who">{who}</span><span>{head}</span></div>
      <p className="slip-quote">{quote}</p>
      <div className="stamp" style={{ borderColor: ink, color: ink }}>{stamp}</div>
    </li>
  );
}

export function Dispatches({ state, autoPrompts }: { state: State; autoPrompts: Record<string, true> }) {
  const autoMoveIds = new Set(promptViews(state).filter((p) => p.move && autoPrompts[p.id]).map((p) => p.move!.id));
  return (
    <section className="dispatches" aria-label="Agent dispatches">
      <div className="panel-head"><h2>DISPATCHES</h2><span>from the three agents</span></div>
      {state.feed.length === 0 ? (
        <p className="slip slip-empty">No dispatches yet. {state.status === "idle" ? "Press START to begin the storm." : "All four corridors are calm."}</p>
      ) : (
        <ul className="slips">
          {state.feed.slice(0, SHOWN).map((item, i) => <Slip key={item.id} item={item} i={i} auto={autoMoveIds.has(item.id)} />)}
        </ul>
      )}
      <p className="note">Agents decide in code. The wording is pre-generated by Gemini and cached.</p>
    </section>
  );
}
